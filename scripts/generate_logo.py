#!/usr/bin/env python3
"""Generate the Material3UI logo SVGs.

The mark is a Material 3 Expressive "cookie" (8 soft lobes) carrying a
rounded "M" built from two Android-style arches, crowned by a tertiary pill:
the Dynamic Island. Only SVG Tiny 1.2 features are used (paths, strokes, linear
and radial gradients, opacity) so Qt's SVG renderer draws it faithfully.

  python3 scripts/generate_logo.py            # writes into the shell's assets
  python3 scripts/generate_logo.py OUT_DIR
"""
import math
import os
import sys

SIZE = 512
CX = CY = SIZE / 2
LOBES = 8
R = 232          # mean radius
DEPTH = 0.055    # lobe depth relative to R
SAMPLES = 96

# Material 3 tonal palette (indigo / violet primary, coral tertiary)
PRIMARY_TOP = "#8B6CFF"
PRIMARY_BOTTOM = "#3D4FD8"
ON_PRIMARY = "#F4F0FF"
TERTIARY = "#FF8A80"


def cookie_path():
    """Closed cubic path through the cookie outline (Catmull-Rom → Bézier)."""
    pts = []
    for i in range(SAMPLES):
        t = 2 * math.pi * i / SAMPLES - math.pi / 2
        r = R * (1 + DEPTH * math.cos(LOBES * (t + math.pi / 2)))
        pts.append((CX + r * math.cos(t), CY + r * math.sin(t)))
    n = len(pts)
    d = [f"M{pts[0][0]:.2f} {pts[0][1]:.2f}"]
    for i in range(n):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f"C{c1[0]:.2f} {c1[1]:.2f} {c2[0]:.2f} {c2[1]:.2f} {p2[0]:.2f} {p2[1]:.2f}")
    return "".join(d) + "Z"


# Rounded "M": two arches sharing the middle leg
STROKE = 50
M_PATH = "M148 372V246A54 54 0 0 1 256 246V336M256 246A54 54 0 0 1 364 246V372"
ISLAND = (206, 120, 100, 34)  # x, y, width, height of the Dynamic Island pill


def full_svg():
    cookie = cookie_path()
    return f"""<svg width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}" fill="none" xmlns="http://www.w3.org/2000/svg">
<!-- Material3UI logo, generated by scripts/generate_logo.py -->
<defs>
<linearGradient id="m3ui-bg" x1="96" y1="40" x2="416" y2="472" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="{PRIMARY_TOP}"/>
<stop offset="1" stop-color="{PRIMARY_BOTTOM}"/>
</linearGradient>
<radialGradient id="m3ui-glow" cx="190" cy="150" r="260" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="#FFFFFF" stop-opacity="0.28"/>
<stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
</radialGradient>
</defs>
<path d="{cookie}" fill="url(#m3ui-bg)"/>
<path d="{cookie}" fill="url(#m3ui-glow)"/>
<path d="{M_PATH}" stroke="{ON_PRIMARY}" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>
<rect x="{ISLAND[0]}" y="{ISLAND[1]}" width="{ISLAND[2]}" height="{ISLAND[3]}" rx="{ISLAND[3] / 2}" fill="{TERTIARY}"/>
</svg>
"""


def symbolic_svg():
    """Single-colour version for tinting (ColorOverlay keeps alpha as tone)."""
    cookie = cookie_path()
    return f"""<svg width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}" fill="none" xmlns="http://www.w3.org/2000/svg">
<!-- Material3UI symbolic logo, generated by scripts/generate_logo.py -->
<path d="{cookie}" fill="#000000" opacity="0.38"/>
<path d="{M_PATH}" stroke="#000000" stroke-width="{STROKE}" stroke-linecap="round" stroke-linejoin="round"/>
<rect x="{ISLAND[0]}" y="{ISLAND[1]}" width="{ISLAND[2]}" height="{ISLAND[3]}" rx="{ISLAND[3] / 2}" fill="#000000"/>
</svg>
"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        here, "..", "dotfiles/.config/quickshell/material3ui/assets/icons")
    os.makedirs(out, exist_ok=True)
    for name, content in (("Material3UI.svg", full_svg()), ("material3ui-symbolic.svg", symbolic_svg())):
        with open(os.path.join(out, name), "w") as f:
            f.write(content)
        print(os.path.join(out, name))


if __name__ == "__main__":
    main()
